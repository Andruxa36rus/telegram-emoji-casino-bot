#!/bin/bash

# run.sh
# Скрипт для запуска бота казино

echo "==================================="
echo "Запуск Casino Bot"
echo "==================================="

# Активация виртуального окружения
echo "🔧 Активация виртуального окружения..."
source casino_bot_env/bin/activate

# Проверка успешности активации
if [ $? -ne 0 ]; then
    echo "❌ Ошибка активации виртуального окружения!"
    echo "Убедитесь, что окружение 'casino_bot_env' существует."
    echo "Запустите ./setup.sh для создания окружения."
    read -p "Нажмите Enter для выхода..."
    exit 1
fi

# Запуск бота
echo "🚀 Запуск main.py..."
python main.py

# Если бот завершился с ошибкой
if [ $? -ne 0 ]; then
    echo ""
    echo "❌ Бот завершился с ошибкой!"
    echo "Проверьте логи выше."
fi

echo ""
read -p "Нажмите Enter для выхода..."
